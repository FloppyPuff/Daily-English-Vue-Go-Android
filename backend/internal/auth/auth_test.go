package auth

import "testing"

func TestPasswordRules(t *testing.T) {
	if PasswordProblem("short1") == "" {
		t.Fatal("short password must fail")
	}
	if PasswordProblem("alllowercase") == "" {
		t.Fatal("password without a digit must fail")
	}
	if PasswordProblem("12345678") == "" {
		t.Fatal("password without a letter must fail")
	}
	if PasswordProblem("good-password1") != "" {
		t.Fatal("valid password was rejected")
	}
}

func TestHashAndVerify(t *testing.T) {
	hashed, err := HashPassword("good-password1")
	if err != nil {
		t.Fatal(err)
	}
	if !VerifyPassword("good-password1", hashed) {
		t.Fatal("correct password did not verify")
	}
	if VerifyPassword("wrong-password1", hashed) {
		t.Fatal("wrong password verified")
	}
	if VerifyPassword("good-password1", "not-a-hash") {
		t.Fatal("malformed hash verified")
	}
}

func TestNodeScryptHashCompatibility(t *testing.T) {
	// Generated by the current Node implementation for GoCompat-Horse1.
	const stored = "scrypt:16384:8:1:FjeYAILKzZWpY1EevS7BYg:SLZRwegN68rndqcmB99PnFFrrhSWGKvcpXUM4Yfm07sLq2NBsOisb7NQzvMxS1_hvX7wd4Kw-VXuwm2W4o4-ig"
	if !VerifyPassword("GoCompat-Horse1", stored) {
		t.Fatal("existing Node scrypt hash did not verify in Go")
	}
	if VerifyPassword("wrong", stored) {
		t.Fatal("wrong password verified against Node hash")
	}
}

func TestTokenIsHashed(t *testing.T) {
	token, hash, err := CreateToken()
	if err != nil {
		t.Fatal(err)
	}
	if token == "" || hash == "" || token == hash {
		t.Fatal("token and hash must be distinct non-empty values")
	}
	if HashToken(token) != hash {
		t.Fatal("hashToken mismatch")
	}
}

func TestEmailNormalization(t *testing.T) {
	if NormalizeEmail("  LEARNER@Example.COM ") != "learner@example.com" {
		t.Fatal("email normalization did not match")
	}
	if EmailProblem("bad") == "" {
		t.Fatal("invalid email accepted")
	}
}
